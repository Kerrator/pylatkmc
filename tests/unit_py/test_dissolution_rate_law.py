def test_rate_law_validator_rejects(tmp_path: Path, kwargs: dict[str, object]) -> None:
    with pytest.raises(ValidationError):
        DissolutionSpec(epsilon_table=tmp_path / "eps.toml", nu_E_Hz=1.0e4, **kwargs)


def test_loader_reads_rate_law(tmp_path: Path) -> None:
    spec_path = write_fixture(
        tmp_path, 'rate_law         = "tafel_ceiling"\nceiling_Hz       = 1.0e13\n'
    )
    spec = loader.load(spec_path)
    assert spec.dissolution is not None
    assert spec.dissolution.rate_law == "tafel_ceiling"
    assert spec.dissolution.ceiling_Hz == 1.0e13
    assert codegen.dissolution_rate_law(spec) == ("tafel_ceiling", 1.0e13)


