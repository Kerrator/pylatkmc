"""Configurable dissolution rate law (``[dissolution].rate_law``).

Covers:
  * the ``DissolutionSpec`` validator (``ceiling_Hz`` required and > ``nu_E_Hz``
    under ``tafel_ceiling``; forbidden under ``clamped``) and the TOML loader;
  * byte-identity of the DEFAULT law: a dissolution-bearing fixture model
    regenerates to the golden sha256s recorded from the pre-``rate_law`` pin
    (pylatkmc 5cf8fb5), with the key omitted AND with an explicit
    ``rate_law = "clamped"``;
  * the ``tafel_ceiling`` emission (proclist.c law-independent, the ceiling
    #define + rewritten ``rateconst_eval`` in proclist.h);
  * C <-> Python agreement: the generated ``rateconst_eval`` (compiled via cc +
    ctypes) matches ``dissolution_rate.dissolution_rate`` under both laws, and
    hop (non-electrochemical) rates are bit-identical across laws.
"""

