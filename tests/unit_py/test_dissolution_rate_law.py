def write_fixture(dirpath: Path, law_lines: str = "") -> Path:
    """Write the golden dissolution-bearing fixture spec (+ ε table) into
    ``dirpath`` and return the spec path. Hops come from the vendored
    ni_example catalogue; dissolution covers Ni and Fe movers, n = 1..9."""
    dirpath.mkdir(parents=True, exist_ok=True)
    (dirpath / "eps.toml").write_text(_FIXTURE_EPS_TOML)
    spec_path = dirpath / "golden_dissolution.kmcspec.toml"
    spec_path.write_text(
        _FIXTURE_SPEC_TOML.format(csv=NI_EXAMPLE_CSV.as_posix(), law_lines=law_lines)
    )
    return spec_path


def _generate(dirpath: Path, law_lines: str = "") -> tuple[bytes, bytes]:
    spec_path = write_fixture(dirpath, law_lines)
    spec = loader.load(spec_path)
    out = dirpath / "generated"
    codegen.generate(spec, out, spec_path=spec_path)
    return (out / "proclist.c").read_bytes(), (out / "proclist.h").read_bytes()


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


