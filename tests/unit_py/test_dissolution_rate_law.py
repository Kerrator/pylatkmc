_TAFEL_LINES = 'rate_law         = "tafel_ceiling"\nceiling_Hz       = 1.0e13\n'


def test_tafel_ceiling_emission(tmp_path: Path) -> None:
    c0, h0 = _generate(tmp_path / "default")
    c1, h1 = _generate(tmp_path / "tafel", _TAFEL_LINES)
    # The rate table / decision tree / apply functions are law-independent.
    assert c1 == c0
    h0s, h1s = h0.decode(), h1.decode()
    assert h1s != h0s
    assert "#define PYLATKMC_DISSOLUTION_CEILING_HZ 10000000000000.0\n" in h1s
    assert "Dissolution rate law: tafel_ceiling" in h1s
    assert "PYLATKMC_DISSOLUTION_CEILING_HZ" not in h0s
    # Exactly one rateconst_eval; the RateConst layout line + size assert unchanged.
    assert h1s.count("static inline double rateconst_eval(") == 1
    for line in h0s.splitlines():
        if line.startswith("typedef struct {") or line.startswith("_Static_assert("):
            assert line in h1s.splitlines()
    # Every default line except the clamped rateconst_eval block survives, in order.
    clamped_block = set(codegen._H_RATECONST_EVAL_CLAMPED.splitlines())
    kept = [ln for ln in h0s.splitlines() if ln not in clamped_block]
    it = iter(h1s.splitlines())
    assert all(any(ln == x for x in it) for ln in kept)


# --------------------------------------------------------------------------
# C rateconst_eval (compiled from the generated header) vs the Python mirror
# --------------------------------------------------------------------------

_SHIM_C = """\
#include "proclist.h"
double shim_rateconst_eval(double prefactor, double Ea, int echem, double T_K, double phi) {
    RateConst rc = { prefactor, Ea, echem, 0 };
    return rateconst_eval(rc, T_K, phi);
}
"""


def _compile_shim(gen_dir: Path, tag: str) -> ctypes.CDLL:
    shim = gen_dir / "shim.c"
    shim.write_text(_SHIM_C)
    ext = "dylib" if os.uname().sysname == "Darwin" else "so"
    lib = gen_dir / f"libshim_{tag}.{ext}"
    cmd = [
        "cc",
        "-std=c11",
        "-Wall",
        "-Wextra",
        "-Werror",
        "-O2",
        "-fPIC",
        "-shared",
        "-I",
        str(gen_dir),
        "-I",
        str(RUNTIME_CORE),
        str(shim),
        "-o",
        str(lib),
        "-lm",
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if res.returncode != 0:
        pytest.fail(f"shim build failed ({tag}):\n{res.stderr}")
    so = ctypes.CDLL(str(lib))
    so.shim_rateconst_eval.restype = ctypes.c_double
    so.shim_rateconst_eval.argtypes = [
        ctypes.c_double,
        ctypes.c_double,
        ctypes.c_int,
        ctypes.c_double,
        ctypes.c_double,
    ]
    return so


@pytest.mark.skipif(shutil.which("cc") is None, reason="cc not on PATH")
def test_c_rateconst_eval_matches_python_mirror(tmp_path: Path) -> None:
    _generate(tmp_path / "default")
    _generate(tmp_path / "tafel", _TAFEL_LINES)
    c_clamped = _compile_shim(tmp_path / "default" / "generated", "clamped")
    c_tafel = _compile_shim(tmp_path / "tafel" / "generated", "tafel")

    eps = {("Fe", "Fe"): EPS_FE_FE, ("Fe", "Ni"): EPS_FE_NI, ("Ni", "Ni"): EPS_FE_NI}
    p_clamped = dr.DissolutionParams(epsilon=eps, nu_E_Hz=1.0e4)
    p_tafel = dr.DissolutionParams(
        epsilon=eps, nu_E_Hz=1.0e4, rate_law="tafel_ceiling", ceiling_Hz=1.0e13
    )
    n_at_ceiling = 0
    for phi in (0.0, 2.50, PHI_TIER1, 6.0):
        for n in range(1, 10):
            for n_fe in range(n + 1):
                hist = {"Fe": n_fe, "Ni": n - n_fe}
                E = dr.e_bare(p_clamped, "Fe", hist)
                py_c = dr.dissolution_rate(p_clamped, "Fe", hist, T_TIER1, phi)
                py_t = dr.dissolution_rate(p_tafel, "Fe", hist, T_TIER1, phi)
                c_c = c_clamped.shim_rateconst_eval(1.0e4, E, 1, T_TIER1, phi)
                c_t = c_tafel.shim_rateconst_eval(1.0e4, E, 1, T_TIER1, phi)
                assert c_c == pytest.approx(py_c, rel=1e-13)
                assert c_t == pytest.approx(py_t, rel=1e-13)
                assert c_t >= c_c  # lifting the floor can only raise the rate
                if phi == PHI_TIER1 and c_t == 1.0e13:
                    n_at_ceiling += 1
    # Fe-only window n <= 9 at phi 3.30 (cf. the w9 table's 54 Fe rows): 27 at the ceiling.
    assert n_at_ceiling == 27

    # Hop (non-electrochemical) rows: bit-identical under both laws, phi ignored.
    for Ea in (-0.1, 0.0, 0.0535, 0.4026, 1.7988, 2.48972):
        for phi in (0.0, PHI_TIER1):
            a = c_clamped.shim_rateconst_eval(1.0e13, Ea, 0, T_TIER1, phi)
            b = c_tafel.shim_rateconst_eval(1.0e13, Ea, 0, T_TIER1, phi)
            assert a == b
            assert a == pytest.approx(
                1.0e13 * math.exp(-max(Ea, 0.0) / (dr.KB_EV_PER_K * T_TIER1)), rel=1e-13
            )
